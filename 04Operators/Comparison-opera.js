// == :Equal to
// != :Not equal to
// ===:Equal to & type or strict version
// !==:Not equal to & type 
//  > , >= , < , <=


x = 5;
y = 2;
console.log("5 == 2 ===>" , x == y);// Equal to

console.log("5 != 2 ===>" ,x != y);//Not Equal


// x = 5
// y = "5"
console.log("5==2 ===>" ,x == y);//this is not strict version
console.log("5===2 ===>" ,x === y);// Equal to & type or strict version

console.log("5!==2 ===>" ,x !== y);//Not double equal to

console.log("5 > 2 ===>" ,x > y);// <
console.log("5 >= 2 ===>" ,x >= y);// <=
console.log("5 < 2 ===>" ,x < y);// >
console.log("5 <= 2 ===>" ,x <= y);// >=




